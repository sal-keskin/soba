/**
 * Regenerates the parameter tables of docs/model.md from src/model/params.ts.
 *   npm run docs:params
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PARAM_TABLE, PEOPLE } from '../src/model/params';

const file = fileURLToPath(new URL('../docs/model.md', import.meta.url));
const label = { lit: 'literature', derived: 'derived', assumed: '**assumed**' } as const;
const num = (v: number): string =>
  v !== 0 && (Math.abs(v) >= 1e5 || Math.abs(v) < 1e-2) ? v.toExponential(2).replace(/\.?0+e/, 'e') : String(v);

const rows = Object.entries(PARAM_TABLE).map(
  ([k, v]) => `| \`${k}\` | ${num(v.value)} | ${v.unit} | ${label[v.status]} | ${v.source} |`,
);
const people = Object.values(PEOPLE).map(
  (q) => `| ${q.kind} | ${q.massKg} | ${q.vb} | ${q.hb} | ${q.va} | ${q.dl} | ${label[q.status]} | ${q.source} |`,
);
const block = [
  '<!-- PARAMS:START (generated by npm run docs:params; edit src/model/params.ts instead) -->',
  '',
  '| Name | Value | Unit | Status | Source or reasoning |',
  '|---|---|---|---|---|',
  ...rows,
  '',
  '**People (CFK inputs)**',
  '',
  '| Person | Mass kg | Blood volume mL | Hb g/mL | Alveolar ventilation mL/min | DL mL/(min·mmHg) | Status | Source or reasoning |',
  '|---|---|---|---|---|---|---|---|',
  ...people,
  '',
  '<!-- PARAMS:END -->',
].join('\n');

const text = readFileSync(file, 'utf8');
const next = text.replace(/<!-- PARAMS:START[\s\S]*<!-- PARAMS:END -->/, block);
if (next === text && !text.includes(block)) throw new Error('PARAMS markers not found in docs/model.md');
writeFileSync(file, next);
const assumed = Object.values(PARAM_TABLE).filter((v) => v.status === 'assumed').length;
console.log(`docs/model.md: ${rows.length} constants (${assumed} assumed), ${people.length} people`);
