const dicts: Record<Lang, Dict> = { tr, en };

let lang: Lang = 'tr';
const listeners: (() => void)[] = [];

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  lang = next;
  try {
    localStorage.setItem('soba-lang', next);
  } catch {
    /* storage may be unavailable; the choice then lasts for this visit only */
  }
  document.documentElement.lang = next;
  for (const fn of listeners) fn();
}

export function initLang(): void {
  let stored: string | null = null;
  try {
    stored = localStorage.getItem('soba-lang');
  } catch {
    /* ignore */
  }
  lang = stored === 'en' ? 'en' : 'tr';
  document.documentElement.lang = lang;
}

export function onLang(fn: () => void): void {
  listeners.push(fn);
}

/** Translate a key, filling {placeholders}. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Locale-aware number with a fixed number of decimals. */
export function num(x: number, digits = 0): string {
  return x.toLocaleString(lang === 'tr' ? 'tr-TR' : 'en-GB', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}

/** All keys, for the consistency test. */
export const DICTS = dicts;
